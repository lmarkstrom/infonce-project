# SimCLR-style augmentation for CIFAR-10 (Appendix E.1)
# ---------------------------------------------------------------------------

class SimCLRAugmentation:
    """
    Standard SimCLR augmentation pipeline for CIFAR-10.

    Paper spec (Appendix E.1):
      - Random resized crop to 32×32 with scale ∈ (0.2, 1.0)
      - Random horizontal flip
      - Color jitter with strengths (brightness, contrast, saturation, hue) = (0.8, 0.8, 0.8, 0.2)
        applied with probability 0.8
      - Random grayscale with probability 0.2

    Args:
        size: Output image size. Default 32 for CIFAR-10.
    """

    def __init__(self, size: int = 32):
        self.transform = T.Compose([
            T.RandomResizedCrop(size=size, scale=(0.2, 1.0)),
            T.RandomHorizontalFlip(),
            T.RandomApply(
                [T.ColorJitter(brightness=0.8, contrast=0.8, saturation=0.8, hue=0.2)],
                p=0.8,
            ),
            T.RandomGrayscale(p=0.2),
            T.ToTensor(),
            T.Normalize(mean=[0.4914, 0.4822, 0.4465],
                        std=[0.2023, 0.1994, 0.2010]),
        ])

    def __call__(self, img):
        """Return two independently augmented views of the same image."""
        return self.transform(img), self.transform(img)


class StandardCIFAR10Transform:
    """
    Standard (non-contrastive) transform for supervised CIFAR-10.

    Used for the supervised baseline in the contrastive vs. supervised
    comparison (Table 1).
    """

    def __init__(self, train: bool = True):
        if train:
            self.transform = T.Compose([
                T.RandomCrop(32, padding=4),
                T.RandomHorizontalFlip(),
                T.ToTensor(),
                T.Normalize(mean=[0.4914, 0.4822, 0.4465],
                            std=[0.2023, 0.1994, 0.2010]),
            ])
        else:
            self.transform = T.Compose([
                T.ToTensor(),
                T.Normalize(mean=[0.4914, 0.4822, 0.4465],
                            std=[0.2023, 0.1994, 0.2010]),
            ])

    def __call__(self, img):
        return self.transform(img)


# ---------------------------------------------------------------------------
# Dataset wrappers that apply augmentations
# ---------------------------------------------------------------------------

class ContrastiveDatasetWrapper(Dataset):
    """
    Wraps any PyTorch dataset to return augmented pairs (view1, view2).

    Compatible with LaplaceDataset, BinaryDataset.

    Args:
        dataset: Base dataset, each item is (x, label).
        augmentation: Callable that takes x (Tensor) and returns (view1, view2).
    """

    def __init__(self, dataset, augmentation):
        self.dataset = dataset
        self.augmentation = augmentation

    def __len__(self) -> int:
        return len(self.dataset)

    def __getitem__(self, idx: int):
        x, label = self.dataset[idx]
        v1, v2 = self.augmentation(x)
        return v1, v2


class GMMContrastiveWrapper(Dataset):
    """
    Wraps GaussianMixtureDataset to return augmented pairs.

    For GMM, positive pairs are two fresh draws from the same component.
    """

    def __init__(self, gmm_dataset, augmentation: GMMComponentAugmentation):
        self.dataset = gmm_dataset
        self.augmentation = augmentation

    def __len__(self) -> int:
        return len(self.dataset)

    def __getitem__(self, idx: int):
        x, component_id = self.dataset[idx]
        v1, v2 = self.augmentation(x, int(component_id))
        return v1, v2


class CIFAR10ContrastiveWrapper(Dataset):
    """
    Wraps torchvision CIFAR-10 to return SimCLR augmented pairs.
    """

    def __init__(self, cifar10_dataset, augmentation: SimCLRAugmentation):
        self.dataset = cifar10_dataset
        self.augmentation = augmentation

    def __len__(self) -> int:
        return len(self.dataset)

    def __getitem__(self, idx: int):
        img, label = self.dataset[idx]
        v1, v2 = self.augmentation(img)
        return v1, v2, label

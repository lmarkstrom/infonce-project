"""
Augmentation strategies used in the paper.

1. SyntheticAugmentation — Gaussian channel + light jitter (Eq. 53, Appendix E.1)
   For Laplace / GMM / Binary synthetic data.

2. BinaryAugmentation — flip 0.1% of zero entries to ones (Appendix E.1)

3. SimCLRAugmentation — standard SimCLR pipeline for CIFAR-10 (Appendix E.1)
"""

from __future__ import annotations

import numpy as np
import torch
import torchvision.transforms as T
import torchvision.transforms.functional as TF
from torch.utils.data import Dataset


# ---------------------------------------------------------------------------
# Synthetic augmentation (Eq. 53)
# ---------------------------------------------------------------------------

class SyntheticAugmentation:
    """
    Augmentation for synthetic vector data (Laplace and GMM settings).

    Two correlated views are generated as:
        x1 = A * x + sqrt(1 - A²) * ε1
        x2 = A * x + sqrt(1 - A²) * ε2

    where ε1, ε2 ~ N(0, I) are independent, and A ∈ (0, 1).

    Then light jitter is applied independently to each view:
      - Additive Gaussian noise with std=0.2
      - Feature dropout with probability p=0.1
      - Random multiplicative scaling by exp(N(0, 0.1²))

    Paper reference: Appendix E.1, Eq. (53).

    Args:
        A: Augmentation correlation parameter. Default 0.6 (paper default).
        noise_std: Additive Gaussian noise std. Default 0.2.
        dropout_p: Feature dropout probability. Default 0.1.
        scale_std: Std of log-multiplicative scale. Default 0.1.
    """

    def __init__(
        self,
        A: float = 0.6,
        noise_std: float = 0.2,
        dropout_p: float = 0.1,
        scale_std: float = 0.1,
    ):
        self.A = A
        self.noise_std = noise_std
        self.dropout_p = dropout_p
        self.scale_std = scale_std
        self._sqrt_one_minus_A2 = np.sqrt(1 - A * A)

    def _apply_jitter(self, x: torch.Tensor) -> torch.Tensor:
        """Light independent jitter per view."""
        # Additive Gaussian noise
        x = x + self.noise_std * torch.randn_like(x)
        # Feature dropout
        mask = torch.bernoulli(torch.full_like(x, 1.0 - self.dropout_p))
        x = x * mask
        # Random multiplicative scaling (scalar per sample)
        log_scale = self.scale_std * torch.randn(1, device=x.device)
        x = x * torch.exp(log_scale)
        return x

    def __call__(self, x: torch.Tensor):
        """
        Generate two augmented views of x.

        Args:
            x: Tensor of shape (d,), a single data point.

        Returns:
            (view1, view2): two augmented Tensors each of shape (d,).
        """
        eps1 = torch.randn_like(x)
        eps2 = torch.randn_like(x)
        v1 = self.A * x + self._sqrt_one_minus_A2 * eps1
        v2 = self.A * x + self._sqrt_one_minus_A2 * eps2
        v1 = self._apply_jitter(v1)
        v2 = self._apply_jitter(v2)
        return v1, v2


class BinaryAugmentation:
    """
    Augmentation for the binary sparse vector dataset.

    Positive pairs are generated by independently flipping a small fraction
    (0.1%) of zero entries to ones (Appendix E.1).

    Args:
        flip_rate: Fraction of zero entries to flip to 1. Default 0.001 (0.1%).
    """

    def __init__(self, flip_rate: float = 0.001):
        self.flip_rate = flip_rate

    def _augment(self, x: torch.Tensor) -> torch.Tensor:
        """Flip flip_rate fraction of zero entries to ones."""
        zero_mask = (x == 0).float()
        flips = torch.bernoulli(zero_mask * self.flip_rate)
        return torch.clamp(x + flips, 0.0, 1.0)

    def __call__(self, x: torch.Tensor):
        return self._augment(x), self._augment(x)


class GMMComponentAugmentation:
    """
    Augmentation for the Gaussian mixture dataset.

    Positive pairs are two independent samples from the same underlying
    mixture component. Since we know the component assignment, we sample
    two i.i.d. draws from N(mean_c, I).

    Args:
        means: Tensor of shape (n_components, dim), the component means.
    """

    def __init__(self, means: torch.Tensor):
        self.means = means  # (n_components, dim)

    def __call__(self, x: torch.Tensor, component_id: int):
        """
        Args:
            x: original sample (unused; we re-sample from the component).
            component_id: integer index of the component.
        """
        mean = self.means[component_id]
        v1 = mean + torch.randn_like(mean)
        v2 = mean + torch.randn_like(mean)
        return v1, v2



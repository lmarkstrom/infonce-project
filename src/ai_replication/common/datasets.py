# 2. Synthetic Gaussian Mixture Model (GMM) Dataset (Appendix E.1)
# ---------------------------------------------------------------------------


class GMMSyntheticDataset:
    """25 equally weighted isotropic Gaussian components in R^{1024} (Appendix E.1).

    Component means are drawn independently at initialization and fixed throughout
    training. Positive pairs are generated by independently sampling two views from
    the same underlying mixture component.
    """

    def __init__(
        self,
        n_train: int = 10_000,
        n_test: int = 5_000,
        d_data: int = 1024,
        n_components: int = 25,
        mean_std: float = 0.05,
        component_std: float = 1.0,
        seed: int = 42,
    ) -> None:
        self.n_train = n_train
        self.n_test = n_test
        self.d_data = d_data
        self.n_components = n_components
        self.component_std = component_std

        gen = torch.Generator().manual_seed(seed)
        self.means = torch.randn((n_components, d_data), generator=gen, dtype=torch.float32) * mean_std
        self.train_components = torch.randint(0, n_components, (n_train,), generator=gen)
        self.test_components = torch.randint(0, n_components, (n_test,), generator=gen)
        self.x_test = (
            self.means[self.test_components]
            + torch.randn((n_test, d_data), generator=gen, dtype=torch.float32) * component_std
        )

    def sample_positive_pair_batch(
        self,
        component_ids: torch.Tensor,
        device: torch.device,
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        """Independently sample two views from the same underlying mixture component."""
        means_batch = self.means.to(device)[component_ids.to(device)]
        x1 = means_batch + torch.randn_like(means_batch) * self.component_std
        x2 = means_batch + torch.randn_like(means_batch) * self.component_std
        return x1, x2

    def get_train_loader(self, batch_size: int = 128) -> DataLoader:
        ds = TensorDataset(self.train_components)
        return DataLoader(ds, batch_size=batch_size, shuffle=True, drop_last=True)



# 4. CIFAR-10 SimCLR & Supervised Data Loaders (Appendix E.1)
# ---------------------------------------------------------------------------


class TwoCropTransform:
    """Apply the same stochastic augmentation pipeline twice to produce a positive pair."""

    def __init__(self, base_transform: Callable[[Any], torch.Tensor]) -> None:
        self.base_transform = base_transform

    def __call__(self, img: Any) -> Tuple[torch.Tensor, torch.Tensor]:
        return self.base_transform(img), self.base_transform(img)


def build_simclr_cifar10_transform(
    use_imagenet_norm: bool = False,
    color_jitter_prob: float = 0.8,
) -> transforms.Compose:
    """SimCLR-style CIFAR-10 augmentation pipeline from Appendix E.1:

    - RandomResizedCrop to 32x32 with scale in (0.2, 1.0)
    - RandomHorizontalFlip
    - ColorJitter with strengths (0.8, 0.8, 0.8, 0.2)
    - RandomGrayscale with probability 0.2
    """
    mean = IMAGENET_MEAN if use_imagenet_norm else CIFAR10_MEAN
    std = IMAGENET_STD if use_imagenet_norm else CIFAR10_STD
    color_jitter = transforms.ColorJitter(brightness=0.8, contrast=0.8, saturation=0.8, hue=0.2)
    jitter_op: Any = (
        transforms.RandomApply([color_jitter], p=color_jitter_prob)
        if color_jitter_prob < 1.0
        else color_jitter
    )
    return transforms.Compose(
        [
            transforms.RandomResizedCrop(32, scale=(0.2, 1.0)),
            transforms.RandomHorizontalFlip(p=0.5),
            jitter_op,
            transforms.RandomGrayscale(p=0.2),
            transforms.ToTensor(),
            transforms.Normalize(mean, std),
        ]
    )


def build_cifar10_eval_transform(use_imagenet_norm: bool = False) -> transforms.Compose:
    """Deterministic evaluation transform for CIFAR-10 test set (10k images)."""
    mean = IMAGENET_MEAN if use_imagenet_norm else CIFAR10_MEAN
    std = IMAGENET_STD if use_imagenet_norm else CIFAR10_STD
    return transforms.Compose(
        [
            transforms.ToTensor(),
            transforms.Normalize(mean, std),
        ]
    )


def build_cifar10_loaders(
    data_dir: str | Path,
    batch_size: int = 256,
    num_workers: int = 2,
    use_imagenet_norm: bool = False,
    download: bool = True,
) -> dict[str, DataLoader]:
    """Create CIFAR-10 train (contrastive & supervised) and test DataLoaders (50k / 10k)."""
    data_dir = str(data_dir)
    simclr_tf = build_simclr_cifar10_transform(use_imagenet_norm=use_imagenet_norm)
    eval_tf = build_cifar10_eval_transform(use_imagenet_norm=use_imagenet_norm)

    train_contrastive_ds = datasets.CIFAR10(
        root=data_dir,
        train=True,
        transform=TwoCropTransform(simclr_tf),
        download=download,
    )
    train_supervised_ds = datasets.CIFAR10(
        root=data_dir,
        train=True,
        transform=simclr_tf,
        download=download,
    )
    train_eval_ds = datasets.CIFAR10(
        root=data_dir,
        train=True,
        transform=eval_tf,
        download=download,
    )
    test_ds = datasets.CIFAR10(
        root=data_dir,
        train=False,
        transform=eval_tf,
        download=download,
    )

    pin = torch.cuda.is_available()
    return {
        "train_contrastive": DataLoader(
            train_contrastive_ds,
            batch_size=batch_size,
            shuffle=True,
            num_workers=num_workers,
            pin_memory=pin,
            drop_last=True,
        ),
        "train_supervised": DataLoader(
            train_supervised_ds,
            batch_size=batch_size,
            shuffle=True,
            num_workers=num_workers,
            pin_memory=pin,
            drop_last=True,
        ),
        "train_eval": DataLoader(
            train_eval_ds,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=pin,
        ),
        "test": DataLoader(
            test_ds,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=pin,
        ),
    }



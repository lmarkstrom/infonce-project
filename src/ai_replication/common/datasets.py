"""Datasets and augmentation channels from Section 5 and Appendix E.1.

Includes:
- Synthetic Laplace(0, 1) dataset with Eq. (53) Gaussian mixing + jitter augmentations
- Synthetic 25-component isotropic Gaussian Mixture Model (GMM) dataset
- Synthetic 1024-dim discrete sparse binary dataset with 0.1% zero->one flip augmentation
- CIFAR-10 SimCLR contrastive and supervised data loaders (50k train / 10k test)
- MS-COCO 2017 validation (images + captions) and ImageNet-R (Sketch / Painting) datasets
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Callable, Tuple

import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset, TensorDataset
from torchvision import datasets, transforms

CIFAR10_MEAN = (0.4914, 0.4822, 0.4465)
CIFAR10_STD = (0.2023, 0.1994, 0.2010)
IMAGENET_MEAN = (0.485, 0.456, 0.406)
IMAGENET_STD = (0.229, 0.224, 0.225)


# ---------------------------------------------------------------------------
# 1. Synthetic Laplace(0, 1) Dataset & Augmentation Channel (Eq. 53)
# ---------------------------------------------------------------------------


def generate_laplace_dataset(
    n_train: int = 20_000,
    n_test: int = 5_000,
    d_data: int = 1024,
    seed: int = 42,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Sample i.i.d. Laplace(0, 1) vectors for training (20k) and testing (5k)."""
    gen = torch.Generator().manual_seed(seed)
    # Inverse CDF sampling for Laplace(0, 1) using deterministic Generator
    u_train = torch.rand((n_train, d_data), generator=gen, dtype=torch.float32) - 0.5
    u_test = torch.rand((n_test, d_data), generator=gen, dtype=torch.float32) - 0.5
    # Clamp away from +-0.5 to prevent log(0)
    eps = 1e-7
    u_train = u_train.clamp(-0.5 + eps, 0.5 - eps)
    u_test = u_test.clamp(-0.5 + eps, 0.5 - eps)
    x_train = -torch.sign(u_train) * torch.log1p(-2.0 * torch.abs(u_train))
    x_test = -torch.sign(u_test) * torch.log1p(-2.0 * torch.abs(u_test))
    return x_train, x_test


def _augment_laplace_single_view(
    x: torch.Tensor,
    corr_a: float = 0.6,
    noise_std: float = 0.2,
    dropout_prob: float = 0.1,
    scale_log_std: float = 0.1,
) -> torch.Tensor:
    """Apply Eq. (53) Gaussian mixing followed by independent jitter from Appendix E.1.

    1. x_view = A * x + sqrt(1 - A^2) * eps,  eps ~ N(0, I)
    2. Additive Gaussian noise with std 0.2
    3. Feature dropout with probability 0.1
    4. Random multiplicative scaling by exp(N(0, 0.1^2))
    """
    b_coeff = math.sqrt(max(1.0 - corr_a * corr_a, 0.0))
    view = corr_a * x + b_coeff * torch.randn_like(x)
    if noise_std > 0.0:
        view = view + noise_std * torch.randn_like(view)
    if dropout_prob > 0.0:
        keep_mask = (torch.rand_like(view) >= dropout_prob).to(view.dtype)
        view = view * keep_mask
    if scale_log_std > 0.0:
        view = view * torch.exp(scale_log_std * torch.randn_like(view))
    return view


def augment_laplace_pair(
    x: torch.Tensor,
    corr_a: float = 0.6,
    noise_std: float = 0.2,
    dropout_prob: float = 0.1,
    scale_log_std: float = 0.1,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Generate two conditionally independent augmented views (x1, x2) given x."""
    v1 = _augment_laplace_single_view(x, corr_a, noise_std, dropout_prob, scale_log_std)
    v2 = _augment_laplace_single_view(x, corr_a, noise_std, dropout_prob, scale_log_std)
    return v1, v2



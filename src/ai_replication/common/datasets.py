# 3. Synthetic Discrete Sparse Binary Dataset (Appendix E.1)
# ---------------------------------------------------------------------------


def generate_sparse_binary_dataset(
    n_train: int = 10_000,
    n_test: int = 5_000,
    d_data: int = 1024,
    sparsity_p: float = 0.05,
    seed: int = 42,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Generate sparse binary vectors in {0, 1}^{1024}.

    Each entry is 1 with probability `sparsity_p` (guaranteeing at least 1 active
    bit per sample so every vector has positive norm).
    """
    gen = torch.Generator().manual_seed(seed)

    def _sample(n: int) -> torch.Tensor:
        x = (torch.rand((n, d_data), generator=gen) < sparsity_p).to(torch.float32)
        zero_rows = x.sum(dim=1) == 0
        if torch.any(zero_rows):
            n_zero = int(zero_rows.sum().item())
            rand_cols = torch.randint(0, d_data, (n_zero,), generator=gen)
            x[zero_rows, rand_cols] = 1.0
        return x

    return _sample(n_train), _sample(n_test)


def augment_sparse_binary_pair(
    x: torch.Tensor,
    flip_zero_prob: float = 0.001,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Independently flip 0.1% of zero entries to ones for each positive view (Appendix E.1)."""
    is_zero = x == 0.0
    flip1 = (torch.rand_like(x) < flip_zero_prob) & is_zero
    flip2 = (torch.rand_like(x) < flip_zero_prob) & is_zero
    v1 = torch.where(flip1, torch.ones_like(x), x)
    v2 = torch.where(flip2, torch.ones_like(x), x)
    return v1, v2



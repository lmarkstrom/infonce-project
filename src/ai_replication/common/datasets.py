class MSCOCOValDataset(Dataset):
    """MS-COCO 2017 validation dataset (5k images + captions) for Table 2, Figs. 6, 9, 10."""

    def __init__(
        self,
        images_dir: str | Path,
        captions_json: str | Path | None = None,
        transform: Callable[[Image.Image], torch.Tensor] | None = None,
    ) -> None:
        self.images_dir = Path(images_dir)
        if not self.images_dir.exists():
            raise FileNotFoundError(f"MS-COCO images directory not found: {self.images_dir}")
        self.transform = transform

        self.samples: list[Tuple[Path, str]] = []
        if captions_json is not None and Path(captions_json).exists():
            with Path(captions_json).open("r", encoding="utf-8") as f:
                ann = json.load(f)
            id_to_file = {img["id"]: img["file_name"] for img in ann["images"]}
            id_to_caption: dict[int, str] = {}
            for item in ann["annotations"]:
                img_id = item["image_id"]
                if img_id not in id_to_caption:
                    id_to_caption[img_id] = item["caption"]
            for img_id, file_name in sorted(id_to_file.items()):
                img_path = self.images_dir / file_name
                if img_path.exists():
                    self.samples.append((img_path, id_to_caption.get(img_id, "")))
        else:
            valid_exts = {".jpg", ".jpeg", ".png"}
            for path in sorted(self.images_dir.iterdir()):
                if path.suffix.lower() in valid_exts:
                    self.samples.append((path, ""))

        if not self.samples:
            raise RuntimeError(f"No images found in MS-COCO directory: {self.images_dir}")

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[Any, str]:
        img_path, caption = self.samples[idx]
        with Image.open(img_path) as im:
            img = im.convert("RGB")
        if self.transform is not None:
            img = self.transform(img)
        return img, caption


class ImageNetRDomainDataset(Dataset):
    """ImageNet-R dataset filtered by artistic rendition domain (e.g. 'sketch', 'painting').

    Supports both the official ImageNet-R directory structure (class synset subfolders
    with filenames prefixed `<domain>_<id>.jpg`) and pre-split domain directories.
    """

    def __init__(
        self,
        root_dir: str | Path,
        domain: str,
        transform: Callable[[Image.Image], torch.Tensor] | None = None,
    ) -> None:
        self.root_dir = Path(root_dir)
        if not self.root_dir.exists():
            raise FileNotFoundError(f"ImageNet-R root directory not found: {self.root_dir}")
        self.domain = domain.lower().strip()
        self.transform = transform

        valid_exts = {".jpg", ".jpeg", ".png", ".webp"}
        domain_subdir = self.root_dir / self.domain
        search_root = domain_subdir if domain_subdir.is_dir() else self.root_dir

        self.image_paths: list[Path] = []
        for path in sorted(search_root.rglob("*")):
            if not path.is_file() or path.suffix.lower() not in valid_exts:
                continue
            if search_root == domain_subdir or path.stem.lower().startswith(f"{self.domain}_"):
                self.image_paths.append(path)

        if not self.image_paths:
            raise RuntimeError(
                f"No images matching domain '{domain}' found under {self.root_dir}. "
                "Expected either a subfolder named after the domain or ImageNet-R filenames "
                "prefixed with '<domain>_' (e.g., 'sketch_0.jpg', 'painting_0.jpg')."
            )

    def __len__(self) -> int:
        return len(self.image_paths)

    def __getitem__(self, idx: int) -> Tuple[Any, str]:
        img_path = self.image_paths[idx]
        with Image.open(img_path) as im:
            img = im.convert("RGB")
        if self.transform is not None:
            img = self.transform(img)
        return img, img_path.name

